K_PER_FILE, RNG, BAUD, N_TIMED, FS = 4, 2031, 460800, 500, 40000
N_IN, N_TGT, TGT_OFF, ROWS_IN, ROWS_TGT = 3248, 5168, 1920, 120, 240
