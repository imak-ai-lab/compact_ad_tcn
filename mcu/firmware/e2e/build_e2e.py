"""Phase 5 / stage 4e: build the end-to-end firmware (raw block -> anomaly score) for the six deployed artifacts.

Usage (from mcu/):  .venv/Scripts/python firmware/e2e/build_e2e.py [tr047_fp32 ...]

Stored data: K = 8 real raw segments, 4 from the normal and 4 from the damaged test file of data/phase5_raw.npz (rng 2031), float32, bit-exact:
3248 samples per channel for reconstruction, 7088 for forecasting (input block + target block, which starts 1920 samples later).
Scorer: inv_cov of the deployed artifact (models/<code>_<art>_cmodel_scorer.npz, stage 3).
Host reference -> data/stage4e_refs.npz: scaled features of the same float32 samples, sr006_dump_bundle.block_features (float64, threshold V1).
Network: the same generated code as stage 4 (firmware/bench/gen/<tag>). Flags: -Os for HAL, network and main (as stage 4), -O3 with loop unrolling for
CMSIS-DSP and features_core.c (as stage 5). Same runtime library, linker script and start-up.
Sizes and RAM -> mcu/firmware_e2e_build.csv.
"""
