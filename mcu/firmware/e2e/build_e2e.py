SCALER_MEAN, SCALER_STD = dump.MEAN, dump.STD


def md5(p: Path) -> str:
    return hashlib.md5(p.read_bytes()).hexdigest()


def run(cmd, **kw):
    res = subprocess.run([str(c) for c in cmd], capture_output=True, text=True, **kw)
    if res.returncode != 0:
        raise RuntimeError(f"failed ({res.returncode}): {' '.join(map(str, cmd))[:300]}\n{res.stdout[-3000:]}\n{res.stderr[-3000:]}")
    return res


def c_arr(name: str, v) -> str:
    return f"const float32_t {name}[{len(v)}] = {{{','.join(f'{float(x):.9e}f' for x in v)}}};\n"


def prepare() -> dict:
    d = np.load(MCU / "data" / "phase5_raw.npz")
    rng = np.random.default_rng(RNG)
    starts = []
    for kind in ("norm", "anom"):
        raw = d[f"raw_{kind}"]
        for s in np.sort(rng.integers(0, raw.shape[1] - SEG[True] - 16, K_PER_FILE)):
            starts.append((kind, int(s) // 16 * 16))   # whole feature rows, as a device would cut them from the stream
    refs = {}
    info = {}
    for fc in (False, True):
        tag = "tl" if fc else "tr"
        x = np.stack([d[f"raw_{k}"][:, s:s + SEG[fc]].astype(np.float32) for k, s in starts])
        refs[f"x_{tag}"] = x
        refs[f"y_in_{tag}"] = np.stack([dump.block_features(b.astype(np.float64), 0, ROWS_IN, FS) for b in x])
        if fc:
            refs["y_tgt_tl"] = np.stack([dump.block_features(b[:, TGT_OFF:TGT_OFF + N_TGT].astype(np.float64), 0, ROWS_TGT, FS) for b in x])
        g = GEN / tag
        shutil.rmtree(g, ignore_errors=True)
        g.mkdir(parents=True)
        h = ["/* generated by build_e2e.py */", "#ifndef E2E_DATA_H", "#define E2E_DATA_H", '#include "arm_math.h"',
             f"#define BENCH_K {len(x)}U", f"#define SEG_N {SEG[fc]}U", f"#define BLOCK_IN_N {N_IN}U", f"#define BLOCK_TGT_N {N_TGT}U", f"#define TGT_OFFSET {TGT_OFF}U",
             f"#define THR_K_V1 {dump.K_V1:.9e}f", f"extern const uint32_t bench_blocks_u32[{x.size}];", "extern const float32_t inv_cov[729];"]
        c = [f"/* generated by build_e2e.py: filters from pywt {pywt.__version__}, raw segments {starts} */", '#include "e2e_data.h"']
        for name in ("sym8", "db4"):
            w = pywt.Wavelet(name)
            lo, hi = np.array(w.rec_lo), np.array(w.rec_hi)
            for k, v in {"dlr": np.array(w.dec_lo)[::-1], "dhr": np.array(w.dec_hi)[::-1], "rle": lo[0::2][::-1], "rlo": lo[1::2][::-1], "rhe": hi[0::2][::-1], "rho": hi[1::2][::-1]}.items():
                h.append(f"extern const float32_t {name}_{k}[{len(v)}];")
                c.append(c_arr(f"{name}_{k}", v))
        h += ["extern const float32_t scaler_mean[27];", "extern const float32_t scaler_std[27];", "#endif"]
        c += [c_arr("scaler_mean", SCALER_MEAN), c_arr("scaler_std", SCALER_STD)]
        u = x.reshape(-1).view(np.uint32)
        c.append(f"__attribute__((aligned(32))) const uint32_t bench_blocks_u32[{x.size}] = {{")
        c += [",".join(f"0x{v:08x}" for v in u[s:s + 12]) + "," for s in range(0, len(u), 12)]
        c.append("};")
        (g / "e2e_data.h").write_text("\n".join(h) + "\n", encoding="ascii")
        (g / "e2e_data.c").write_text("\n".join(c) + "\n", encoding="ascii")
        info[fc] = x.size * 4
    np.savez(MCU / "data" / "stage4e_refs.npz", **refs, source=np.array([f"{k}:{s}" for k, s in starts]), rng=RNG)
    print("segments", starts, flush=True)
    return info


def cc(src: Path, obj: Path, opt: list[str], inc: list[Path], defs: list[str]):
    obj.parent.mkdir(parents=True, exist_ok=True)
    res = run([GCC_BIN / "arm-none-eabi-gcc", *CPU, *opt, *COMMON_FLAGS, *defs, *[f"-I{p}" for p in inc], "-c", src, "-o", obj])
    return res.stderr


def common_objects() -> dict:
    """HAL, start-up (-Os) and CMSIS-DSP (-O3): the same objects for every model; DSP needs no model-specific define."""
    inc = [VAL / "Core" / "Inc", HAL / "Inc", HAL / "Inc" / "Legacy", DEV / "Include", CORE, DSP / "Include", DSP / "PrivateInclude"]
    objs = []
    srcs_os = [VAL / "Core" / "Src" / "stm32h7xx_it.c", VAL / "Core" / "Src" / "stm32h7xx_hal_msp.c",
               DEV / "Source" / "Templates" / "system_stm32h7xx_dualcore_bootcm7_cm4gated.c", DEV / "Source" / "Templates" / "gcc" / "startup_stm32h755xx.s"]
    srcs_os += [HAL / "Src" / f"stm32h7xx_hal{s}.c" for s in HAL_SRC]
    for s in srcs_os:
        o = OBJ / "os" / (s.stem + ".o")
        if not o.exists():
            cc(s, o, ["-Os"], inc, DEFS)
        objs.append(o)
    for s in DSP_SRC:
        src = DSP / "Source" / s
        o = OBJ / "o3" / (src.stem + ".o")
        if not o.exists():
            cc(src, o, ["-O3"], inc, DEFS)
        objs.append(o)
    return dict(objs=objs, inc=inc)


def build(tag: str, com: dict, blocks_b: dict) -> list[dict]:
    code, art = tag.split("_")
    code = code.upper()
    fc = code == "TL082"
    gtag = "tl" if fc else "tr"
    gen, g = BENCH_GEN / tag, GEN / gtag
    bld = HERE / "build" / tag
    shutil.rmtree(bld, ignore_errors=True)
    bld.mkdir(parents=True)
    defs = DEFS + [f"-DBENCH_TAG=e2e_{tag}", f"-DBENCH_FORECAST={int(fc)}"]
    inc = [g, gen, AI / "Inc", *com["inc"]]
    objs = list(com["objs"])
    warn = ""
    # scorer of this artifact
    inv = np.load(MCU / "models" / f"{code}_{art}_cmodel_scorer.npz")["inv_cov"].astype(np.float32)
    assert inv.shape == (27, 27)
    (bld / "scorer.c").write_text('#include "e2e_data.h"\n' + c_arr("inv_cov", inv.reshape(-1)), encoding="ascii")
    for src, opt in ((HERE / "main.c", ["-Os"]), (HERE / "features_core.c", ["-O3"]), (bld / "scorer.c", ["-Os"]), (g / "e2e_data.c", ["-Os"]),
                     (gen / "network.c", ["-Os"]), (gen / "network_data.c", ["-Os"]), (gen / "network_data_params.c", ["-Os"])):
        o = bld / (src.stem + ".o")
        warn += cc(src, o, opt, inc, defs)
        objs.append(o)
    elf = bld / f"bench_e2e_{tag}.elf"
    res = run([GCC_BIN / "arm-none-eabi-gcc", *CPU, *objs, "-specs=nano.specs", "-specs=nosys.specs", f"-T{VAL / 'STM32H755ZITx_CM7.ld'}", f"-L{LIB_DIR}", f"-l:{LIB}", "-lc", "-lm",
               "-Wl,--gc-sections", f"-Wl,-Map={bld / elf.with_suffix('.map').name}", "-Wl,--print-memory-usage", "-o", elf])
    (bld / "build.log").write_text(res.stdout + res.stderr + "\n" + warn, encoding="utf-8")
    run([GCC_BIN / "arm-none-eabi-objcopy", "-O", "binary", "-S", elf, elf.with_suffix(".bin")])
    sizes = {}
    for line in run([GCC_BIN / "arm-none-eabi-size", "-A", elf]).stdout.splitlines():
        m = re.match(r"^(\.\S+)\s+(\d+)\s+(\d+)", line)
        if m:
            sizes[m.group(1)] = int(m.group(2))
    syms = {}
    for line in run([GCC_BIN / "arm-none-eabi-nm", "-S", "--size-sort", "-t", "d", elf]).stdout.splitlines():
        p = line.split()
        if len(p) == 4:
            syms[p[3]] = int(p[1])
    flash = sum(v for k, v in sizes.items() if k in FLASH_SECTIONS)
    cyc_b = syms.get("cyc", 0)
    static_ram = sizes[".data"] + sizes[".bss"] + sizes[".ai_pool"] - cyc_b
    feat_ram = sum(syms.get(k, 0) for k in ("g_block", "g_rows_in", "g_rows_tgt", "g_coef", "g_ext", "g_fft_in", "g_fft_out", "g_wext", "g_a1"))
    w_main = re.findall(r"^.*(?:main|features_core)\.c.*warning:.*$", warn, re.M)
    base = dict(date=now(), host=host_tag(), tag=tag, code=code, artifact=f"{code}_{art}.onnx", seed=selection[code], firmware=elf.name, bin_md5=md5(elf.with_suffix(".bin")),
                main_c_md5=md5(HERE / "main.c"), core_c_md5=md5(HERE / "features_core.c"), flash_B=flash, blocks_B=blocks_b[fc], flash_without_blocks_B=flash - blocks_b[fc],
                data_B=sizes[".data"], bss_B=sizes[".bss"], ai_pool_B=sizes[".ai_pool"], cyc_buffer_B=cyc_b, static_ram_B=static_ram, feature_buffers_B=feat_ram,
                activations_B=syms.get("pool0", 0), warnings=len(w_main))
    rows = [{**base, "check": "flash_le_2MiB", "value": flash, "reference": 2 * 1024 * 1024, "status": verdict(flash <= 2 * 1024 * 1024)},
            {**base, "check": "no_warnings_in_own_code", "value": len(w_main), "reference": 0, "status": verdict(not w_main)}]
    print(f"{tag}: flash {flash / 1024:.1f} KiB (without blocks {(flash - blocks_b[fc]) / 1024:.1f}), static RAM {static_ram / 1024:.1f} KiB "
          f"(.data {sizes['.data'] / 1024:.1f}, .bss {sizes['.bss'] / 1024:.1f}, pool {sizes['.ai_pool'] / 1024:.1f}), feature buffers {feat_ram / 1024:.1f} KiB, warnings {len(w_main)}", flush=True)
    for w in w_main[:8]:
        print("  ", w[-150:])
    return rows


if __name__ == "__main__":
    tags = sys.argv[1:] or [f"{c.lower()}_{a}" for c in MODELS for a in ("fp32", "int8")]
    info = prepare()
    com = common_objects()
    rows = []
    for t in tags:
        rows += build(t, com, info)
    append_csv(OUT, rows, fresh=len(tags) == 6)
    for r in rows:
        print(r["status"], r["firmware"], r["check"], r["value"], r["reference"])
    if any(r["status"] == "FAIL" for r in rows):
        raise SystemExit(1)
