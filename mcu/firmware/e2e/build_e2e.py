HAL_SRC = ["", "_cortex", "_rcc", "_rcc_ex", "_gpio", "_pwr", "_pwr_ex", "_flash", "_flash_ex", "_uart", "_uart_ex", "_dma", "_dma_ex", "_mdma", "_exti", "_hsem"]
DSP_SRC = ["TransformFunctions/arm_rfft_fast_f32.c", "TransformFunctions/arm_cfft_f32.c", "TransformFunctions/arm_cfft_radix8_f32.c",
           "TransformFunctions/arm_bitreversal2.c", "CommonTables/arm_common_tables.c", "CommonTables/arm_const_structs.c", "BasicMathFunctions/arm_dot_prod_f32.c"]
FLASH_SECTIONS = {".isr_vector", ".text", ".rodata", ".ARM.extab", ".ARM", ".preinit_array", ".init_array", ".fini_array", ".data"}
