"""Phase 5 / stage 4a: build the own benchmark firmware (NUCLEO-H755ZI-Q, Cortex-M7).

Usage (from mcu/):  .venv/Scripts/python firmware/bench/build_bench.py [tag ...]
  tags: tr047_fp32 ... tr138_int8 (run builds) and idle (baseline build). Default: all six + idle.
  env P5_CLK=HSI -> HSI clock builds (tag suffix _hsi), for runs with the ST-LINK unpowered.

Per code, once (same windows for fp32 and int8):
  K = 50 real PU test windows (25 normal + 25 anomalous, rng 2027) of the deployed seed's windowing,
  stored bit-exact (float32 -> uint32) in firmware/bench/gen/windows_<code>/bench_windows.c;
  indices -> data/stage4_windows_<code>.npz and mcu/bench_windows.csv.
  K is limited by flash: 50 x 12 960 B = 633 KiB fits next to the largest model (TR138 fp32);
  the 1000 timed inferences cycle over the K windows (window i % K).
Per tag:
  1. `stedgeai generate` with the stage-2/3 options (p5common.CUBEAI_OPTS), c-name "network";
  2. arm-none-eabi-gcc 14.2 with the same CPU/opt flags, defines, HAL/CMSIS sources, linker script
     and NetworkRuntime library as the stage-3 firmware (firmware/validation/build_validation.py);
     no aiValidation stack;
  3. section sizes -> mcu/firmware_bench_build.csv (flash <= 2 MiB, .ai_pool == stage-2 activations).
The idle build uses the TR047 fp32 network (initialised, never run).
"""
from __future__ import annotations

import csv
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import zlib
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
MCU = HERE.parent.parent
VAL = HERE.parent / "validation"
sys.path.insert(0, str(MCU))
from p5common import (CKPT_DIR, CUBEAI_OPTS, MODELS, STEDGEAI, append_csv, build_windows, cubeai_env,  # noqa: E402
                      host_tag, now, verdict)

GCC_BIN = Path(r"C:\ST\arm-gnu-14.2\bin")
AI = Path(STEDGEAI).parents[2] / "Middlewares" / "ST" / "AI"
TP = HERE.parent / "third_party"
HAL = TP / "stm32h7xx-hal-driver"
DEV = TP / "cmsis-device-h7"
CORE = TP / "CMSIS_5" / "CMSIS" / "Core" / "Include"
LIB_DIR = AI / "Lib" / "GCC" / "STM32H7"
LIB = "NetworkRuntime1020_CM7_GCC.a"
OUT = MCU / "firmware_bench_build.csv"
WIN_CSV = MCU / "bench_windows.csv"

K_PER_CLASS, WIN_SEED, N_TIMED = 25, 2027, 1000
CLK = os.environ.get("P5_CLK", "HSE").upper()
assert CLK in ("HSE", "HSI"), CLK
SUFFIX = "_hsi" if CLK == "HSI" else ""

CPU = ["-mcpu=cortex-m7", "-mthumb", "-mfpu=fpv5-d16", "-mfloat-abi=hard"]
OPT = ["-Os", "-g3"]                                  # same as the stage-3 firmware
BAUD = 460800
DEFS = ["-DSTM32H755xx", "-DCORE_CM7", "-DUSE_HAL_DRIVER", "-DUSE_PWR_DIRECT_SMPS_SUPPLY", "-DUSE_NUCLEO_H755ZI_Q",
        f"-DVALIDATION_BAUDRATE={BAUD}U", f"-DBENCH_N={N_TIMED}U", f"-DBENCH_CLK_HSI={int(CLK == 'HSI')}"]
HAL_SRC = ["", "_cortex", "_rcc", "_rcc_ex", "_gpio", "_pwr", "_pwr_ex", "_flash", "_flash_ex", "_uart",
           "_uart_ex", "_dma", "_dma_ex", "_mdma", "_exti", "_hsem"]
FLASH_SECTIONS = {".isr_vector", ".text", ".rodata", ".ARM.extab", ".ARM", ".preinit_array", ".init_array",
                  ".fini_array", ".data"}
selection = json.loads((CKPT_DIR / "selection.json").read_text())


def md5(p: Path) -> str:
    return hashlib.md5(p.read_bytes()).hexdigest()


def run(cmd, **kw):
    res = subprocess.run([str(c) for c in cmd], capture_output=True, text=True, **kw)
    if res.returncode != 0:
        raise RuntimeError(f"failed ({res.returncode}): {' '.join(map(str, cmd))[:300]}\n{res.stdout[-3000:]}\n{res.stderr[-3000:]}")
    return res


def stage2_activations() -> dict:
    with (MCU / "cubeai_summary.csv").open(encoding="utf-8") as fh:
        return {r["artifact"].removesuffix(".onnx").lower(): int(r["activations_rw_B"]) for r in csv.DictReader(fh)}


def prepare_windows(code: str) -> tuple[Path, list[dict]]:
    """K balanced test windows, channel-first [27, 120] float32 as the ONNX/Cube.AI input."""
    seed = selection[code]
    cfg = json.loads((CKPT_DIR / f"{code}_s{seed}.config.json").read_text())
    x, _, lab = build_windows(cfg, "test")
    rng = np.random.default_rng(WIN_SEED)
    idx = np.concatenate([rng.choice(np.flatnonzero(lab == c), K_PER_CLASS, replace=False) for c in (0, 1)])
    rng.shuffle(idx)                                   # interleave normal / anomalous in the stored order
    xw = np.ascontiguousarray(x[idx].transpose(0, 2, 1)).astype(np.float32)   # [K, 27, 120]
    (MCU / "data").mkdir(exist_ok=True)
    np.savez(MCU / "data" / f"stage4_windows_{code}.npz", idx=idx, label=lab[idx], x=xw, seed=WIN_SEED,
             n_test=len(lab))
    d = HERE / "gen" / f"windows_{code.lower()}"
    shutil.rmtree(d, ignore_errors=True)
    d.mkdir(parents=True)
    u = xw.reshape(-1).view(np.uint32)
    k, per = xw.shape[0], xw[0].size
    (d / "bench_windows.h").write_text(
        "/* generated by build_bench.py: K real PU test windows, float32 bit patterns */\n"
        "#ifndef BENCH_WINDOWS_H\n#define BENCH_WINDOWS_H\n#include <stdint.h>\n"
        f"#define BENCH_K {k}U\n#define BENCH_WIN_WORDS {per}U\n"
        f"extern const uint32_t bench_windows_u32[{k * per}];\n"
        f"extern const uint8_t bench_window_label[{k}];\n#endif\n", encoding="ascii")
    lines = [f"/* generated by build_bench.py: {code}, seed {seed}, test windows {idx.tolist()} */",
             '#include "bench_windows.h"',
             f"__attribute__((aligned(32))) const uint32_t bench_windows_u32[{k * per}] = {{"]
    for s in range(0, len(u), 12):
        lines.append(",".join(f"0x{v:08x}" for v in u[s:s + 12]) + ",")
    lines.append("};")
    lines.append(f"const uint8_t bench_window_label[{k}] = {{{','.join(str(int(v)) for v in lab[idx])}}};")
    (d / "bench_windows.c").write_text("\n".join(lines) + "\n", encoding="ascii")
    rows = [dict(date=now(), code=code, seed=seed, k=j, test_window_index=int(i), label=int(lab[i]),
                 crc32_in=f"{zlib.crc32(xw[j].tobytes()):08x}", rng=WIN_SEED, n_test_windows=len(lab),
                 layout="float32 [27,120] channel-first")
            for j, i in enumerate(idx)]
    print(f"{code}: windows {k} ({int(lab[idx].sum())} anomalous) of {len(lab)} test windows, "
          f"array crc32={zlib.crc32(xw.tobytes()):08x}", flush=True)
    return d, rows


def build(tag: str, act_ref: dict, win_dirs: dict) -> list[dict]:
    idle = tag == "idle"
    net_tag = "tr047_fp32" if idle else tag
    code, art = net_tag.split("_")
    code = code.upper()
    out_tag = tag + SUFFIX
    gen, bld = HERE / "gen" / net_tag, HERE / "build" / out_tag
    shutil.rmtree(bld, ignore_errors=True)
    bld.mkdir(parents=True)
    if not (gen / "network.c").exists() or os.environ.get("P5_REGEN"):
        shutil.rmtree(gen, ignore_errors=True)
        gen.mkdir(parents=True)
        run([STEDGEAI, "generate", "--model", MCU / "models" / f"{code}_{art}.onnx", *CUBEAI_OPTS[art], "--name",
             "network", "--workspace", gen / "ws", "--output", gen], env=cubeai_env())
        shutil.rmtree(gen / "ws", ignore_errors=True)
    wdir = win_dirs[code]

    src = [HERE / "main.c", VAL / "Core" / "Src" / "stm32h7xx_it.c", VAL / "Core" / "Src" / "stm32h7xx_hal_msp.c",
           wdir / "bench_windows.c"]
    src += [gen / f for f in ("network.c", "network_data.c", "network_data_params.c")]
    src += [DEV / "Source" / "Templates" / "system_stm32h7xx_dualcore_bootcm7_cm4gated.c",
            DEV / "Source" / "Templates" / "gcc" / "startup_stm32h755xx.s"]
    src += [HAL / "Src" / f"stm32h7xx_hal{s}.c" for s in HAL_SRC]
    inc = [VAL / "Core" / "Inc", gen, wdir, HAL / "Inc", HAL / "Inc" / "Legacy", DEV / "Include", CORE, AI / "Inc"]
    elf = bld / f"bench_{out_tag}.elf"
    ld = VAL / "STM32H755ZITx_CM7.ld"
    defs = DEFS + [f"-DBENCH_TAG={out_tag}", f"-DBENCH_IDLE={int(idle)}"]
    cmd = [GCC_BIN / "arm-none-eabi-gcc", *CPU, *OPT, *defs, "-std=c11", "-Wall", "-ffunction-sections",
           "-fdata-sections", *[f"-I{p}" for p in inc], *src,
           "-specs=nano.specs", "-specs=nosys.specs", f"-T{ld}", f"-L{LIB_DIR}", f"-l:{LIB}", "-lc", "-lm",
           "-Wl,--gc-sections", f"-Wl,-Map={bld / ('bench_' + out_tag + '.map')}", "-Wl,--print-memory-usage",
           "-o", elf]
    res = run(cmd)
    (bld / "build.log").write_text(" ".join(map(str, cmd)) + "\n\n" + res.stdout + res.stderr, encoding="utf-8")
    run([GCC_BIN / "arm-none-eabi-objcopy", "-O", "binary", "-S", elf, elf.with_suffix(".bin")])
    run([GCC_BIN / "arm-none-eabi-objcopy", "-O", "ihex", elf, elf.with_suffix(".hex")])

    sizes = {}
    for line in run([GCC_BIN / "arm-none-eabi-size", "-A", elf]).stdout.splitlines():
        m = re.match(r"^(\.\S+)\s+(\d+)\s+(\d+)", line)
        if m:
            sizes[m.group(1)] = (int(m.group(2)), int(m.group(3)))
    flash = sum(s for k, (s, _) in sizes.items() if k in FLASH_SECTIONS)
    dtcm = sum(s for k, (s, a) in sizes.items() if 0x20000000 <= a < 0x20020000)
    axi = sum(s for k, (s, a) in sizes.items() if 0x24000000 <= a < 0x24080000)
    pool = sizes.get(".ai_pool", (0, 0))[0]
    win_bytes = (wdir / "bench_windows.h").read_text()
    kk = int(re.search(r"BENCH_K (\d+)U", win_bytes).group(1))
    ww = int(re.search(r"BENCH_WIN_WORDS (\d+)U", win_bytes).group(1))
    ref_act = act_ref.get(net_tag)
    warn = len(re.findall(r"warning:", res.stderr))
    gcc_ver = run([GCC_BIN / "arm-none-eabi-gcc", "--version"]).stdout.splitlines()[0]
    base = dict(date=now(), host=host_tag(), gcc=gcc_ver, stedgeai_options=" ".join(CUBEAI_OPTS[art]),
                runtime_lib=f"{LIB_DIR.name}/{LIB} md5={md5(LIB_DIR / LIB)}", cflags=" ".join(CPU + OPT + defs),
                main_c_md5=md5(HERE / "main.c"), code=code, artifact=f"{code}_{art}.onnx", mode="idle" if idle else "run",
                clk=CLK, firmware=elf.name, bin_md5=md5(elf.with_suffix(".bin")), flash_B=flash,
                windows_B=kk * ww * 4, flash_without_windows_B=flash - kk * ww * 4, dtcm_B=dtcm, axi_B=axi,
                ai_pool_B=pool, gcc_warnings=warn)
    rows = [
        {**base, "check": "flash_le_2MiB", "value": flash, "reference": 2 * 1024 * 1024, "status": verdict(flash <= 2 * 1024 * 1024)},
        {**base, "check": "ai_pool_eq_stage2_activations", "value": pool, "reference": ref_act,
         "status": verdict(ref_act is not None and abs(pool - ref_act) < 32)},
        {**base, "check": "dtcm_le_128KiB", "value": dtcm, "reference": 128 * 1024, "status": verdict(dtcm <= 128 * 1024)},
        {**base, "check": "axi_le_512KiB", "value": axi, "reference": 512 * 1024, "status": verdict(axi <= 512 * 1024)},
    ]
    print(f"{out_tag}: flash={flash / 1024:.1f} KiB (windows {kk * ww * 4 / 1024:.1f} KiB) dtcm={dtcm} axi={axi} "
          f"pool={pool} (stage2 {ref_act}) warnings={warn}", flush=True)
    return rows


if __name__ == "__main__":
    all_tags = [f"{c.lower()}_{a}" for c in MODELS for a in ("fp32", "int8")] + ["idle"]
    tags = sys.argv[1:] or all_tags
    codes = sorted({("TR047" if t == "idle" else t.split("_")[0].upper()) for t in tags})
    win_dirs, win_rows = {}, []
    for c in codes:
        win_dirs[c], r = prepare_windows(c)
        win_rows += r
    append_csv(WIN_CSV, win_rows, fresh=len(codes) == len(MODELS))
    act_ref = stage2_activations()
    rows = []
    for t in tags:
        rows += build(t, act_ref, win_dirs)
    append_csv(OUT, rows, fresh=(tags == all_tags and CLK == "HSE"))
    for r in rows:
        print(f"{r['status']} {r['firmware']:28} {r['check']}: {r['value']} ref={r['reference']}")
    if any(r["status"] == "FAIL" for r in rows):
        raise SystemExit(1)
